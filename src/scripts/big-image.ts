/* =============================================================================
 * 灯箱换图 —— **打开就是那张大档本身**。
 *
 * ── 为什么不再"先小后大"（2026-10-15 站主：「把他换成和大图尺寸一样」）
 *   这一台原来先拿 800 档顶上、再在后台换成 1280 档，理由是站主 2026-10-08 说过
 *   「点大图太慢了」。**这次是同一个诉求的另一半**：那段"看着是糊的"时间本身就是
 *   「太慢」的一种 —— 读者先看到一张放大后发虚的图，再等它变清楚。
 *   ⇒ 站主要的是"点开看到的就是那张图"，那就不该先递一张小的过去。
 *
 *   代价是诚实的，说清楚（量的是本站 82 帧真实产物，不是估的）：
 *     · 800 档  中位 53.2 KB / 均值 63.4 KB（合计 5.1 MB）
 *     · 1280 档 中位 92.1 KB / 均值 115.7 KB / 最大 475.1 KB（合计 9.3 MB）
 *   ⇒ 中位数只差 **1.7 倍**，多数帧"多等的那点"远小于"看糊图的时间"；
 *     但**最重的那 4 张（>300 KB）在慢网上会有一段空白**（无占位可显示）。
 *     这是拿"偶尔空白一下"换"永远不出现糊图"，不是白赚的。
 *   ★ 前提没变：**原图不部署**，产物里最大的就是 1280 档
 *     （`scripts/gen-gallery-webp.mjs`：30 MB 静态站不合理）。要真全尺寸是另一个决定。
 *
 * ── 刻意不做的事
 *   · 不预取"用户可能点的下一张"：那会把 1280 档整个拖进首屏（合计 9.3 MB）。
 *     这一台的主张是"点开才取"（有门闩守着：打开灯箱之前不许产生大档请求）。
 *   · 不加第二个 `<img>` 双图层淡入淡出：省掉一次布局，DOM 保持单张。
 *   · 不做"先画个框再填"：本站灯箱底色本来就深，空一下不刺眼。
 *
 * ── 与谁共用
 *   两套灯箱都走这里：砖墙 `PhotoWall.astro`（`/gallery/<册>/`）与
 *   螺旋盘 `SpiralPlate.astro`（`/gallery/spiral/`、`/gallery/`）。
 *   抽成一个模块，是为了"以后只改一处"—— 两边各抄一份必然腐化。
 * -------------------------------------------------------------------------- */

/**
 * 把大档换到 `img` 上。
 *
 * @param img 灯箱那一只 `<img>`
 * @param big 大档地址（`a[href]`，服务端就写好；1280 档）
 */
export function showBig(img: HTMLImageElement, big: string): void {
  /* 同一张不重设：翻页绕回来时不该再闪一下。
     ⚠ 判据要连 `src` 一起看 —— 关灯箱时会把它摘掉（"不留空 src"那条规定），
       只比 dataset 的话，再打开同一张就什么都不显示了。 */
  if (img.dataset.big === big && img.getAttribute('src')) return;
  img.dataset.big = big;
  const el = img as HTMLImageElement & { fetchPriority?: string };
  el.fetchPriority = 'high';   // 灯箱里这一张就是当前页面的主角
  /* 打开这一刻容器才可见 ⇒ 把它从 lazy 放行。
     ★ 为什么不在 HTML 里就去掉 `loading="lazy"`：那样页面加载时
       （容器 display:none 但属性是 eager）会**立刻**去拉大档 ——
       正好是要避免的那次请求。时机应该落在"真的打开"这一刻。 */
  img.loading = 'eager';
  /* ★ 一次赋值就到位，不再"先小后大"：浏览器自己管解码，
     换图那一刻也不会出现"白一下又出来"（那是 onload 换图才有的毛病）。 */
  img.src = big;
}